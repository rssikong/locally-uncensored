// Alle Selektoren als flache Liste, fuer den Trockenlauf. Funktionen werden mit einem Beispielwert gerufen.
export function alleSelektoren(baum = S, pfad = 'S') {
  const aus = []
  for (const [k, v] of Object.entries(baum)) {
    const p = `${pfad}.${k}`
    if (typeof v === 'function') {
      const s = v.length >= 2 ? v('beispiel', tid('m-models-download')) : v('beispiel')
      if (s && s.sel) aus.push({ pfad: `${p}(...)`, ...s, parametrisch: true })
    } else if (v && typeof v === 'object' && 'sel' in v) aus.push({ pfad: p, ...v })
    else if (v && typeof v === 'object') aus.push(...alleSelektoren(v, p))
  }
  return aus
}
